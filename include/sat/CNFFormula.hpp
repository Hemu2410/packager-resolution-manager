#ifndef CNF_FORMULA_HPP
#define CNF_FORMULA_HPP

#include "Clause.hpp"
#include "Literal.hpp"
#include <vector>
#include <string>
#include <map>
#include <fstream>
#include <sstream>
#include <iostream>

class CNFFormula {
private:
    int numVariables;
    std::vector<Clause> clauses;
    std::map<std::string, int> nameToVar;
    std::map<int, std::string> varToName;

public:
    CNFFormula() : numVariables(0) {}

    int getNumVariables() const {
        return numVariables;
    }

    size_t getNumClauses() const {
        return clauses.size();
    }

    const std::vector<Clause>& getClauses() const {
        return clauses;
    }

    void addClause(const Clause& clause) {
        clauses.push_back(clause);
    }

    void addClause(const std::vector<Literal>& lits) {
        clauses.push_back(Clause(lits));
    }

    int getOrCreateVariable(const std::string& name) {
        auto it = nameToVar.find(name);
        if (it != nameToVar.end()) {
            return it->second;
        }
        numVariables++;
        nameToVar[name] = numVariables;
        varToName[numVariables] = name;
        return numVariables;
    }

    int getVariable(const std::string& name) const {
        auto it = nameToVar.find(name);
        if (it != nameToVar.end()) {
            return it->second;
        }
        return 0; // Not found
    }

    std::string getVariableName(int var) const {
        auto it = varToName.find(var);
        if (it != varToName.end()) {
            return it->second;
        }
        return "X" + std::to_string(var);
    }

    const std::map<std::string, int>& getNameToVarMap() const {
        return nameToVar;
    }

    std::string toDIMACS() const {
        std::stringstream ss;
        ss << "c Generated by Constraint-Based Package Resolver (MFCS Project)\n";
        for (const auto& kv : varToName) {
            ss << "c " << kv.first << " = " << kv.second << "\n";
        }
        ss << "p cnf " << numVariables << " " << clauses.size() << "\n";
        for (const auto& clause : clauses) {
            for (const auto& lit : clause.literals) {
                ss << lit.toInt() << " ";
            }
            ss << "0\n";
        }
        return ss.str();
    }

    bool exportDIMACS(const std::string& filepath) const {
        std::ofstream out(filepath);
        if (!out.is_open()) return false;
        out << toDIMACS();
        return true;
    }

    static CNFFormula fromDIMACS(const std::string& filepath) {
        std::ifstream in(filepath);
        if (!in.is_open()) {
            throw std::runtime_error("Cannot open DIMACS file: " + filepath);
        }

        CNFFormula formula;
        std::string line;
        while (std::getline(in, line)) {
            if (line.empty()) continue;
            if (line[0] == 'c') {
                // Comment, check for variable mapping "c <id> = <name>"
                std::stringstream ss(line);
                char c;
                int id;
                std::string eq, name;
                if (ss >> c >> id >> eq >> name && eq == "=") {
                    formula.nameToVar[name] = id;
                    formula.varToName[id] = name;
                }
                continue;
            }
            if (line[0] == 'p') {
                std::stringstream ss(line);
                std::string p, cnf;
                int nVars, nClauses;
                ss >> p >> cnf >> nVars >> nClauses;
                formula.numVariables = nVars;
                continue;
            }

            // Clause line
            std::stringstream ss(line);
            int litVal;
            std::vector<Literal> lits;
            while (ss >> litVal) {
                if (litVal == 0) break;
                lits.push_back(Literal(litVal));
                if (std::abs(litVal) > formula.numVariables) {
                    formula.numVariables = std::abs(litVal);
                }
            }
            if (!lits.empty()) {
                formula.addClause(Clause(lits));
            }
        }
        return formula;
    }

    std::string toString() const {
        std::string s;
        for (size_t i = 0; i < clauses.size(); i++) {
            if (i > 0) s += " ^ ";
            s += clauses[i].toString();
        }
        return s;
    }
};

#endif // CNF_FORMULA_HPP
